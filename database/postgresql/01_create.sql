-- RENT A WEDDING DRESS - PostgreSQL schema
-- Translation of CreateDatabase.sql (SQL Server → PostgreSQL)
-- Mirrors the EF Core model in RentAWeddingDressAPI.Core
--
-- IMPORTANT: identifiers are QUOTED to match the EF Core model
-- exactly (Npgsql emits "Users", "U_id" with preserved case).
--
-- Run with:  psql "$CONN" -f 01_create.sql
-- (database "RentAWeddingDress" must already exist)
-- =============================================================

-- 1. TABLES

-- Users (+ credit balance for penalty, + rider role)
CREATE TABLE IF NOT EXISTS "Users" (
    "U_id"         INT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    "Name"         VARCHAR(200) NOT NULL,
    "Contact"      VARCHAR(100) NOT NULL UNIQUE,
    "Password"     VARCHAR(510) NOT NULL,
    "CreditBalance" DECIMAL(10,2) NULL DEFAULT 0,
    "Role"         VARCHAR(20) NOT NULL DEFAULT 'customer'  -- 'customer' | 'rider'
);

-- User Addresses (+ map pin from Google Maps)
CREATE TABLE IF NOT EXISTS "UserAddress" (
    "UA_id"     INT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    "U_id"      INT NOT NULL REFERENCES "Users"("U_id"),
    "Address"   TEXT NOT NULL,
    "Latitude"  DECIMAL(9,6) NULL,
    "Longitude" DECIMAL(9,6) NULL
);

-- Dress Categories
CREATE TABLE IF NOT EXISTS "DressCategory" (
    "Category_id" INT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    "Cname"       VARCHAR(100) NOT NULL UNIQUE
);

-- Sub Categories
CREATE TABLE IF NOT EXISTS "SubCategory" (
    "SubCategory_id" INT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    "Category_id"    INT NOT NULL REFERENCES "DressCategory"("Category_id"),
    "SCname"         VARCHAR(100) NOT NULL
);

-- Sizes
CREATE TABLE IF NOT EXISTS "Sizes" (
    "Size_id"   INT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    "SizeName"  VARCHAR(20) NOT NULL UNIQUE
);

-- Dresses (+ age/condition + shop location)
CREATE TABLE IF NOT EXISTS "Dress" (
    "D_id"          INT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    "U_id"          INT NOT NULL REFERENCES "Users"("U_id"),
    "Category_id"   INT NOT NULL REFERENCES "DressCategory"("Category_id"),
    "SubCategory_id" INT NOT NULL REFERENCES "SubCategory"("SubCategory_id"),
    "Condition"     INT NULL DEFAULT 5,
    "Dtitle"        VARCHAR(300) NOT NULL,
    "Description"   TEXT,
    "Gender"        VARCHAR(20) NOT NULL,
    "RentPrice"     DECIMAL(18,2) NOT NULL,
    "AgeYears"      INT NULL DEFAULT 0,
    "AgeMonths"     INT NULL DEFAULT 0,
    "AgeDays"       INT NULL DEFAULT 0,
    "Latitude"      DECIMAL(9,6) NULL,
    "Longitude"     DECIMAL(9,6) NULL
);

-- Dress Images (multiple images per dress)
CREATE TABLE IF NOT EXISTS "DressImages" (
    "DI_id"   INT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    "D_id"    INT NOT NULL REFERENCES "Dress"("D_id") ON DELETE CASCADE,
    "ImgPath" TEXT NOT NULL
);

-- Dress Occasions (multiple occasions per dress)
CREATE TABLE IF NOT EXISTS "DressOccasion" (
    "Occasion_id" INT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    "D_id"        INT NOT NULL REFERENCES "Dress"("D_id") ON DELETE CASCADE,
    "Occasion"    VARCHAR(100) NOT NULL
);

-- Dress Sizes junction (+ stock for multi-copy)
CREATE TABLE IF NOT EXISTS "DressSizes" (
    "DS_id"   INT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    "D_id"    INT NOT NULL REFERENCES "Dress"("D_id") ON DELETE CASCADE,
    "Size_id" INT NOT NULL REFERENCES "Sizes"("Size_id"),
    "Stock"   INT NULL DEFAULT 1
);

-- Booking Requests (+ cancellation / penalty fields)
CREATE TABLE IF NOT EXISTS "BookingRequest" (
    "BR_id"         INT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    "U_id"          INT NOT NULL REFERENCES "Users"("U_id"),
    "UserAddressID" INT NOT NULL REFERENCES "UserAddress"("UA_id"),
    "StartingDate"  TIMESTAMP NOT NULL,
    "ReturnDate"    TIMESTAMP NOT NULL,
    "NoOfDays"      INT NOT NULL,
    "Status"        INT NULL DEFAULT 0,  -- 0=Pending 1=Accepted 2=Cancelled 3=Rejected 4=Picked 5=PickupConfirmed 6=ReturnRequested 7=Completed
    "CancelledDate" TIMESTAMP NULL,
    "PenaltyAmount" DECIMAL(10,2) NULL DEFAULT 0,
    "Rider_id"      INT NULL REFERENCES "Users"("U_id")  -- rider who accepted the delivery
);

-- Booking Details (+ multi-size quantity)
-- One BookingRequest can have MANY BookingDetails (2M + 1S + 4XL = 3 rows)
CREATE TABLE IF NOT EXISTS "BookingDetail" (
    "BD_id"      INT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    "BR_id"      INT NOT NULL REFERENCES "BookingRequest"("BR_id") ON DELETE CASCADE,
    "D_id"       INT NOT NULL REFERENCES "Dress"("D_id"),
    "TotalPrice" DECIMAL(18,2) NOT NULL,
    "Feedback"   TEXT,
    "Rating"     INT NULL,
    "Quantity"   INT NULL DEFAULT 1,
    "Size_id"    INT  -- no FK (legacy rows may be NULL)
);

